#!/usr/bin/env bash
# ==============================================================================
# Lite Office OS — Early Boot QEMU Test Harness
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

RAM="${1:-512M}"
KERNEL="${PROJECT_ROOT}/output/vmlinuz-6.6-lite"
INITRD="${PROJECT_ROOT}/output/initramfs-x86_64.img"
LOG_FILE="${PROJECT_ROOT}/output/qemu_early_boot_${RAM}.log"

echo -e "${BLUE}==============================================================================${NC}"
echo -e "${BLUE}Lite Office OS — QEMU Early Boot Verification (RAM: ${RAM})${NC}"
echo -e "${BLUE}==============================================================================${NC}"

if [ ! -f "$KERNEL" ]; then
    echo -e "${RED}[-] Error: Kernel image '$KERNEL' not found. Run Stage 2 build first.${NC}"
    exit 1
fi

if [ ! -f "$INITRD" ]; then
    echo -e "${RED}[-] Error: Initramfs image '$INITRD' not found.${NC}"
    exit 1
fi

echo "[*] Launching QEMU headless with serial console redirected to: $LOG_FILE"
rm -f "$LOG_FILE"

QEMU_ARGS=(
    -m "$RAM"
    -smp 2
    -kernel "$KERNEL"
    -initrd "$INITRD"
    -append "console=ttyS0 initrd=initramfs.img break=1"
    -nographic
    -no-reboot
    -serial file:"$LOG_FILE"
    -monitor none
)

# Use hardware acceleration if KVM is available and functional
if qemu-system-x86_64 -accel kvm -display none -serial none </dev/null >/dev/null 2>&1; then
    echo -e "    ${GREEN}[+] KVM Hardware Acceleration enabled!${NC}"
    QEMU_ARGS+=(-accel kvm -cpu host)
else
    echo -e "    ${YELLOW}[!] Running in TCG software emulation mode.${NC}"
    QEMU_ARGS+=(-accel tcg -cpu qemu64)
fi

# Run QEMU in background
qemu-system-x86_64 "${QEMU_ARGS[@]}" &
QEMU_PID=$!

# Wait up to 30 seconds for boot banner in log
BOOTED=0
for i in $(seq 1 30); do
    sleep 1
    if grep -q "Lite Office OS — Early Userspace Bootloader" "$LOG_FILE" 2>/dev/null; then
        BOOTED=1
        break
    fi
done

# Terminate QEMU process
kill -9 "$QEMU_PID" 2>/dev/null || true
wait "$QEMU_PID" 2>/dev/null || true

echo "[*] Analyzing boot log..."
if [ ! -f "$LOG_FILE" ]; then
    echo -e "${RED}[-] FAIL: No log file generated by QEMU.${NC}"
    exit 1
fi

# 1. Check for kernel panics
if grep -q "Kernel panic" "$LOG_FILE"; then
    echo -e "${RED}[-] KERNEL PANIC DETECTED:${NC}"
    grep -C 3 "Kernel panic" "$LOG_FILE"
    exit 1
fi

# 2. Check for Linux banner
if grep -q "Linux version" "$LOG_FILE"; then
    KERNEL_LINE=$(grep "Linux version" "$LOG_FILE" | head -n 1)
    echo -e "    - Kernel Banner: ${GREEN}PASS${NC} ($KERNEL_LINE)"
else
    echo -e "    - Kernel Banner: ${RED}FAIL${NC}"
    cat "$LOG_FILE" | tail -n 20
    exit 1
fi

# 3. Check for detected memory
if grep -q "Memory:" "$LOG_FILE" || grep -q "Detected Memory" "$LOG_FILE"; then
    MEM_LINE=$(grep -E "Memory:|Detected Memory" "$LOG_FILE" | head -n 2 | tr '\n' ' ')
    echo -e "    - Memory Init  : ${GREEN}PASS${NC} ($MEM_LINE)"
fi

# 4. Check for Initramfs userspace execution
if grep -q "Lite Office OS — Early Userspace Bootloader" "$LOG_FILE"; then
    echo -e "    - Initramfs Run: ${GREEN}PASS (Early Userspace initialized and executed successfully!)${NC}"
else
    echo -e "    - Initramfs Run: ${RED}FAIL (Early userspace banner not observed in log)${NC}"
    echo "Last 30 lines of log:"
    tail -n 30 "$LOG_FILE"
    exit 1
fi

echo -e "${BLUE}==============================================================================${NC}"
echo -e "${GREEN}[V] QEMU EARLY BOOT TEST PASSED WITH ${RAM} RAM!${NC}"
echo -e "${BLUE}==============================================================================${NC}"
exit 0
